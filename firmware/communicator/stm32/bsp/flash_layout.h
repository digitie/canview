/** @file flash_layout.h @brief OTA §5의 STM32G474 DBANK=1 고정 BSP 배치. */
#ifndef CANVIEW_STM_BSP_FLASH_LAYOUT_H
#define CANVIEW_STM_BSP_FLASH_LAYOUT_H

#define CANVIEW_STM_FLASH_BASE (0x08000000U)
#define CANVIEW_STM_FLASH_BYTES (0x00080000U)
#define CANVIEW_STM_FLASH_PAGE_BYTES (2048U)
#define CANVIEW_STM_FLASH_WRITE_BYTES (8U)
#define CANVIEW_STM_BOOT_BYTES (0x00010000U)
#define CANVIEW_STM_PRIMARY_ADDRESS (0x08010000U)
#define CANVIEW_STM_PRIMARY_BYTES (0x00030000U)
#define CANVIEW_STM_SECONDARY_ADDRESS (0x08040000U)
#define CANVIEW_STM_SECONDARY_BYTES (0x00030800U)
#define CANVIEW_STM_POLICY_A_ADDRESS (0x08070800U)
#define CANVIEW_STM_POLICY_B_ADDRESS (0x08071800U)
#define CANVIEW_STM_POLICY_BYTES (0x00001000U)
#define CANVIEW_STM_CONFIG_A_ADDRESS (0x08072800U)
#define CANVIEW_STM_CONFIG_B_ADDRESS (0x08076800U)
#define CANVIEW_STM_CONFIG_BYTES (0x00004000U)
#define CANVIEW_STM_RESERVED_ADDRESS (0x0807A800U)
#define CANVIEW_STM_RESERVED_BYTES (0x00005800U)
#define CANVIEW_STM_IMAGE_HEADER_BYTES (512U)
#define CANVIEW_STM_SIGNED_IMAGE_MAX_BYTES (180U * 1024U)
#define CANVIEW_STM_PRIMARY_VECTOR (CANVIEW_STM_PRIMARY_ADDRESS + CANVIEW_STM_IMAGE_HEADER_BYTES)
#define CANVIEW_STM_SECONDARY_IMAGE (CANVIEW_STM_SECONDARY_ADDRESS + CANVIEW_STM_FLASH_PAGE_BYTES)

#endif
